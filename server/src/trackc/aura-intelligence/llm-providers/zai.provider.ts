// 50K tokens/day budget — you'll never hit the budget.
//
// HOW TO GET YOUR ZAI_TOKEN:
//   The z-ai CLI auto-generates a token on first use. To get it:
//     1. Run `z-ai chat -p "hello"` on any server with z-ai installed
//     2. Read the token from /etc/.z-ai-config or ~/.z-ai-config
//     3. Copy the "token" field value
