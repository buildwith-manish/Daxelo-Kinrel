//   automatically. For the NestJS server, we read the token from:
//     1. ZAI_TOKEN env var (preferred — set this on Render)
//     2. /etc/.z-ai-config file (auto-generated by the z-ai CLI)
//     3. ~/.z-ai-config file
//
// Configuration (set via Render env vars):
