//   - ZAI_BASE_URL: Optional. Defaults to https://internal-api.z.ai/v1
//   - ZAI_DEFAULT_MODEL: Optional. Defaults to 'glm-4.6'
//   - ZAI_USER_ID: Optional. Your Z.ai user ID (from config)
//   - ZAI_CHAT_ID: Optional. A chat session ID
